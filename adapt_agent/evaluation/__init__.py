"""Evaluation frameworks for LLM agents."""

import logging
from typing import Any, Callable, Optional

logger = logging.getLogger(__name__)


class AgentEvaluator:
    """Evaluates LLM agent performance and behavior.

    Provides comprehensive evaluation metrics and benchmarking
    capabilities for agent quality assessment.
    """

    def __init__(self, max_results: int = 1000):
        """Initialize the AgentEvaluator.

        Args:
            max_results: Maximum number of evaluation results to store in memory.
        """
        self.max_results = max_results
        self._evaluation_results: list[dict[str, Any]] = []
        self._custom_metrics: dict[str, Callable] = {}

    def register_metric(
        self,
        name: str,
        metric_func: Callable[[Any, Any], float],
    ) -> None:
        """Register a custom evaluation metric.

        Args:
            name: Name of the metric
            metric_func: Function that computes the metric score
        """
        self._custom_metrics[name] = metric_func

    def evaluate_response(
        self,
        agent_id: str,
        input_data: Any,
        output_data: Any,
        expected_output: Optional[Any] = None,
    ) -> dict[str, Any]:
        """Evaluate an agent's response.

        Args:
            agent_id: Unique identifier for the agent
            input_data: Input provided to agent
            output_data: Output generated by agent
            expected_output: Expected output (if available)

        Returns:
            Evaluation results
        """
        results = {
            "agent_id": agent_id,
            "input": input_data,
            "output": output_data,
            "expected": expected_output,
            "metrics": {},
        }

        # Apply custom metrics
        for metric_name, metric_func in self._custom_metrics.items():
            try:
                score = metric_func(output_data, expected_output)
                results["metrics"][metric_name] = score
            except Exception as e:
                logger.error(f"Error computing metric {metric_name}: {e}")
                results["metrics"][metric_name] = None

        self._evaluation_results.append(results)

        # SECURITY: Prevent unbounded memory growth
        if len(self._evaluation_results) > self.max_results:
            self._evaluation_results.pop(0)

        return results

    def compute_aggregate_metrics(
        self,
        agent_id: Optional[str] = None,
    ) -> dict[str, float]:
        """Compute aggregate metrics across evaluations.

        Args:
            agent_id: Optional agent ID to filter results

        Returns:
            Dictionary of aggregate metric scores
        """
        if not self._evaluation_results:
            return {}

        sums = {}
        counts = {}

        # ⚡ Bolt: Integrated filter condition directly into the main iteration loop
        # to avoid instantiating an intermediate filtered list, reducing memory allocation
        # and redundant O(N) traversal overhead.
        for result in self._evaluation_results:
            if agent_id and result["agent_id"] != agent_id:
                continue

            for metric_name, score in result["metrics"].items():
                if score is not None:
                    sums[metric_name] = sums.get(metric_name, 0.0) + score
                    counts[metric_name] = counts.get(metric_name, 0) + 1

        return {name: sums[name] / count for name, count in counts.items() if count > 0}

    def get_evaluation_results(
        self,
        agent_id: Optional[str] = None,
        limit: Optional[int] = None,
    ) -> list[dict[str, Any]]:
        """Get evaluation results.

        Args:
            agent_id: Filter by agent ID
            limit: Maximum number of results to return

        Returns:
            List of evaluation results
        """
        # ⚡ Bolt: Using reversed() with early-exit limits O(N) operations to O(limit)
        if limit is not None:
            results = []
            for r in reversed(self._evaluation_results):
                if agent_id and r["agent_id"] != agent_id:
                    continue
                results.append(r)
                if len(results) >= limit:
                    break
            results.reverse()
            return results

        results = self._evaluation_results
        if agent_id:
            results = [r for r in results if r["agent_id"] == agent_id]

        return results


__all__ = ["AgentEvaluator"]
